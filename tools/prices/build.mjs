// 値段らしい数字（3桁以上か桁区切り付き）だけを「何かの値段」にする。「60 min」「90分」のような短い数字は文字どおりに照合（取り違え防止）
const skel = (x) => reEsc(x).replace(/[0-9]{1,3}(?:,[0-9]{3})+(?:\\\.[0-9]+)?|[0-9]{3,}(?:\\\.[0-9]+)?/g, '[0-9][0-9,]*(?:\\.[0-9]+)?');
// 目印の端が数字の途中（「฿2,」など）にならないよう、数字の切れ目まで伸ばす
const NUMCH = /[0-9.,]/;
function widen(txt, a, b) { while (a > 0 && NUMCH.test(txt[a]) && NUMCH.test(txt[a - 1])) a--; while (b < txt.length && NUMCH.test(txt[b - 1]) && NUMCH.test(txt[b])) b++; return [a, b]; }
// 目印は「文字どおり」でも「値段の数字をゆるめても」本文で1か所に決まる長さにする（似た表の行を取り違えない）
function anchor(txt, st, en, pl, ql) {
  for (let i = 0; i < 60; i++) {
    const [a0, b0] = widen(txt, Math.max(0, st - pl), Math.min(txt.length, en + ql));
    const pre = txt.slice(a0, st), post = txt.slice(en, b0), mid = txt.slice(st, en); const nd = pre + mid + post;
    const a1 = txt.indexOf(nd);
    if (a1 >= 0 && txt.indexOf(nd, a1 + 1) < 0) { const m = findOne(txt, skel(pre) + skel(mid) + skel(post)); if (m && m !== 'many') return [pre, post]; }
    pl += 16; ql += 10;
  }
  return [txt.slice(Math.max(0, st - pl), st), txt.slice(en, en + ql)];
}
// まず文字どおりに探し（1か所なら確定）、無ければ値段の数字をゆるめて探す（1か所なら確定）。戻り値は findOne と同じ形
function locate(s, parts) {
  const lit = parts.join('');
  const a = s.indexOf(lit);
  if (a >= 0 && s.indexOf(lit, a + 1) < 0) { const m = [lit, ...parts.slice(0, -1)]; m.index = a; return m; }
  if (a >= 0) return 'many';
  return findOne(s, parts.slice(0, -1).map((x) => '(' + skel(x) + ')').join('') + skel(parts[parts.length - 1]));
}
function findOne(s, reSrc) { const ms = [...s.matchAll(new RegExp(reSrc, 'g'))]; return ms.length === 1 ? ms[0] : (ms.length ? 'many' : null); }
const visibleNow = (id) => !!resolve(id);
