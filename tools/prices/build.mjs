#!/usr/bin/env node
// Ciel ホームページの値段・メニューを管理画面（原本）から作り直す。依存なし（Node 18+）。
//
//   node tools/prices/build.mjs          … 書き換える（GitHub Actions が1時間ごとに実行・手動でも可）
//   node tools/prices/build.mjs --check  … 書き換えずに、ずれと壊れた配線だけ報告（終了コード 1＝要対応）
//
// 原本: Firestore menus コレクション（管理画面で保存 → masterWrite → publishMirrors が書く。アプリも同じものを読む）
// 書き換える物:
//   1. data/menu.json                        … メニュー表のデータ（公開メニューだけ・管理画面の並び順）
//   2. menu*.html の #menu の中身              … 静的なメニュー表（JS が無くても見える・Google 用）。開くとブラウザが最新で描き直す
//   3. menu*.html / index*.html の構造化データ  … OfferCatalog / makesOffer（Google 向けの値段一覧）
//   4. 全ページの構造化データの Offer（"sku": "fsXX" が付いた物）… price / minPrice / maxPrice
//   5. 文章中の値段（data/price-slots.json に登録された1か所ずつ）… 「฿2,990〜4,500」の数字部分
// 追加・変更・非表示・削除: 1〜4 は自動で出る/消える。5 の文章は、メニューが非公開・削除になったら書き換えずに
//   data/price-report.json に「孤立」として出し、終了コード 1（GitHub が失敗メールを送る）。
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..');
const R = require(path.join(ROOT, 'assets', 'menu-render.js'));
const CHECK = process.argv.includes('--check');
const rd = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const changed = [];
const wr = (f, s) => { if (rd(f) !== s) { changed.push(f); if (!CHECK) fs.writeFileSync(path.join(ROOT, f), s); } };

// ── 原本を読む ──
const rows = await R.fetchAll(fetch);
if (!rows.length) { console.error('menus が空（読み取り失敗）→ 何も書き換えない'); process.exit(2); }
const byId = Object.fromEntries(rows.map((m) => [m.id, m]));
const cats = R.model(rows);
const visIds = new Set(cats.flatMap((c) => c.items.map((i) => i.id)));
const report = { at: new Date().toISOString(), menus: visIds.size, orphans: [], broken: [], changed: [] };

// カテゴリの最安（文章の「カット ฿1,000〜」など。特別 id min:xxx）
// 前髪・キッズ・既存客のみ（Returning Client Only）は「〜から」の代表に入れない（「カット ฿1,000〜」が前髪の ฿400 にならないように）
const MIN_CATS = { cut: ['Hair Cut'], colour: ['Hair Colour'], straight: ['Perm'], headspa: ['Japanese Head Spa'], treatment: ['Treatment'] };
const MIN_SKIP = /fringe|kid|returning|前髪|キッズ|既存/i;
function resolve(id) {
  if (id.startsWith('min:')) {
    const keys = MIN_CATS[id.slice(4)] || [];
    const its = cats.filter((c) => keys.includes(c.key)).flatMap((c) => c.items).filter((i) => !MIN_SKIP.test(i.name.en + ' ' + i.name.ja));
    if (!its.length) return null;
    const lo = its.reduce((a, b) => (b.price < a.price ? b : a));
    return { price: lo.price, max: null, from: true };
  }
  if (!visIds.has(id)) return null; // 非公開・削除 → 孤立
  const m = byId[id];
  return { price: Number(m.price) || 0, max: R.maxOf(m), from: R.fromOf(m), pct: Number(m.percent) || 0 };
}
// 値段スロットの書き方
//  fmt "n"  … 「2,990」（数字だけ）
//  fmt "r"  … 「2,990〜4,500」「2,990〜」「1,200」（sep は元の区切り記号）
//  fmt "x"  … 上限の数字だけ「4,500」（上限が無くなったら開始価格）
//  fmt "pct" … クーポンの割引率の数字（「（20%OFF）」の 20）
function render(slot, v) {
  if (slot.fmt === 'x') return R.fmt(v.max != null ? v.max : v.price);
  if (slot.fmt === 'pct') return v.pct ? String(v.pct) : slot.cur; // クーポンの割引率「20%OFF」の数字（割引率の無い定額クーポンはそのまま）
  if (slot.fmt === 'r') return R.fmt(v.price) + (v.max != null ? slot.sep + R.fmt(v.max) : (v.from ? slot.sep : ''));
  return R.fmt(v.price);
}

// ── 1. data/menu.json ──
const menuJson = { source: 'admin (Firestore menus) — generated by tools/prices/build.mjs. Do not edit by hand.', categories: cats.map((c) => ({
  label: c.key, slug: c.slug, cat: c.title,
  items: c.items.map((it) => ({ id: it.id, name: it.name.en, names: it.name, price: it.priceText, min: it.price, max: it.max, off: it.off, dur: { ja: R.durText(it.dur, 'ja'), en: R.durText(it.dur, 'en'), th: R.durText(it.dur, 'th') }, desc: it.desc }))
})) };
wr('data/menu.json', JSON.stringify(menuJson, null, 1) + '\n');

// ── 構造化データの書き換えヘルパ ──
function eachLd(s, fn) {
  return s.replace(/(<script type="application\/ld\+json">)([\s\S]*?)(<\/script>)/g, (all, a, body, b) => {
    let j; try { j = JSON.parse(body); } catch (e) { return all; }
    const before = JSON.stringify(j);
    fn(j);
    return JSON.stringify(j) === before ? all : a + JSON.stringify(j) + b;
  });
}
function walk(o, fn) { if (Array.isArray(o)) o.forEach((x) => walk(x, fn)); else if (o && typeof o === 'object') { fn(o); Object.values(o).forEach((x) => walk(x, fn)); } }
const OFFERS = R.offers(cats);
const LANG_OF = (f) => (/\.en\.html$/.test(f) ? 'en' : /\.th\.html$/.test(f) ? 'th' : 'ja');

const htmlFiles = fs.readdirSync(ROOT).filter((f) => f.endsWith('.html'));
for (const f of htmlFiles) {
  let s = rd(f);
  const lang = LANG_OF(f);
  // 2. メニュー表（menu*.html）: <div id="menu"> … </div><!--/menu-->
  if (/^menu(\.(en|th))?\.html$/.test(f)) {
    s = s.replace(/<div id="menu"[^>]*>[\s\S]*?<\/div><!--\/menu-->/, () => '<div id="menu">' + R.html(cats, lang) + '</div><!--/menu-->');
  }
  // 3. メニュー全体の Offer 一覧
  s = eachLd(s, (j) => {
    if (j['@type'] === 'OfferCatalog' && Array.isArray(j.itemListElement) && /Menu/i.test(j.name || '')) j.itemListElement = OFFERS;
    walk(j, (o) => { if (Array.isArray(o.makesOffer)) o.makesOffer = OFFERS; });
    // 4. 個別ページの Offer（sku 付き）
    walk(j, (o) => {
      if (o['@type'] !== 'Offer' || !o.sku || o === undefined) return;
      if (OFFERS.includes(o)) return;
      const v = resolve(String(o.sku));
      if (!v) { report.orphans.push({ f, where: 'jsonld', id: o.sku }); return; }
      o.price = String(v.price);
      if (v.max != null) o.priceSpecification = { '@type': 'PriceSpecification', minPrice: String(v.price), maxPrice: String(v.max), priceCurrency: 'THB' };
      else if (o.priceSpecification) delete o.priceSpecification;
    });
  });
  wr(f, s);
}

// ── 5. 文章中の値段（スロット）──
const SLOTS_FILE = 'data/price-slots.json';
const slots = fs.existsSync(path.join(ROOT, SLOTS_FILE)) ? JSON.parse(rd(SLOTS_FILE)) : [];
const byFile = {};
slots.forEach((sl, k) => { (byFile[sl.f] = byFile[sl.f] || []).push(k); });
for (const [f, ks] of Object.entries(byFile)) {
  if (!fs.existsSync(path.join(ROOT, f))) { ks.forEach((k) => report.broken.push({ ...slots[k], why: 'file missing' })); continue; }
  let s = CHECK ? rd(f) : rd(f); // 2〜4 で書き換えた後の内容
  // 位置を先に全部見つける（隣り合うスロットが互いの目印に入っていても狂わない）
  const found = [];
  for (const k of ks) {
    const sl = slots[k];
    const needle = sl.pre + sl.cur + sl.post;
    const at = s.indexOf(needle);
    if (at < 0 || s.indexOf(needle, at + 1) >= 0) { report.broken.push({ f, id: sl.id, cur: sl.cur, pre: sl.pre.slice(-30), why: at < 0 ? '目印が見つからない（ページの文章が変わった）' : '目印が2か所以上' }); continue; }
    found.push({ k, start: at + sl.pre.length, end: at + sl.pre.length + sl.cur.length });
  }
  found.sort((a, b) => b.start - a.start);
  for (const x of found) {
    const sl = slots[x.k];
    const v = resolve(sl.id);
    if (!v) { report.orphans.push({ f, where: 'text', id: sl.id, cur: sl.cur, pre: sl.pre.slice(-40) }); continue; }
    const next = render(sl, v);
    if (next !== sl.cur) { s = s.slice(0, x.start) + next + s.slice(x.end); x.delta = next; }
  }
  // 目印（前後の文字）を書き換え後の本文から取り直す
  const ordered = found.slice().sort((a, b) => a.start - b.start);
  let shift = 0;
  for (const x of ordered) {
    const sl = slots[x.k];
    const start = x.start + shift;
    const val = x.delta != null ? x.delta : sl.cur;
    if (x.delta != null) shift += x.delta.length - sl.cur.length;
    sl.cur = val;
    sl.pre = s.slice(Math.max(0, start - sl.pre.length), start);
    sl.post = s.slice(start + val.length, start + val.length + sl.post.length);
  }
  wr(f, s);
}
wr(SLOTS_FILE, JSON.stringify(slots, null, 0).replace(/\},\{/g, '},\n{') + '\n');

report.changed = changed.filter((f) => f !== SLOTS_FILE);
if (!CHECK) fs.writeFileSync(path.join(ROOT, 'data', 'price-report.json'), JSON.stringify({ ...report, changed: report.changed }, null, 1) + '\n');
console.log(`menus=${report.menus} changed=${report.changed.length} orphans=${report.orphans.length} broken=${report.broken.length}`);
report.changed.forEach((f) => console.log('  changed', f));
report.orphans.forEach((o) => console.log('  ORPHAN', JSON.stringify(o)));
report.broken.forEach((o) => console.log('  BROKEN', JSON.stringify(o)));
process.exit(report.orphans.length || report.broken.length ? 1 : 0);
