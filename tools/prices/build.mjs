// ── 構造化データの書き換えヘルパ ──
// 構造化データは元の書式（Python json.dumps と同じ「, 」「: 」区切り・日本語はそのまま）で書き戻す。書式が変わると文章の目印がずれる
function pyDumps(v) {
  if (v === null || typeof v !== 'object') return JSON.stringify(v).replace(/[\u007f-\uffff]/g, (c) => c).replace(/\//g, '/');
  if (Array.isArray(v)) return '[' + v.map(pyDumps).join(', ') + ']';
  return '{' + Object.entries(v).map(([k, x]) => JSON.stringify(k) + ': ' + pyDumps(x)).join(', ') + '}';
}
function eachLd(s, fn) {
  ldIndex = 0;
  return s.replace(/(<script type="application\/ld\+json">)([\s\S]*?)(<\/script>)/g, (all, a, body, b) => {
    ldIndex++;
    let j; try { j = JSON.parse(body); } catch (e) { return all; }
    const before = JSON.stringify(j);
    fn(j);
    const out = pyDumps(j);
    return (JSON.stringify(j) === before && out === body) ? all : a + out + b;
  });
}
// 空になった配列にも戻せるよう、配列は全部見る
function walkArrays(o, key, fn) { if (Array.isArray(o)) { fn(o, key); o.forEach((x, i) => walkArrays(x, key + '[' + i + ']', fn)); } else if (o && typeof o === 'object') Object.entries(o).forEach(([k, v]) => walkArrays(v, key + '.' + k, fn)); }
